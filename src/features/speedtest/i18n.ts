export type SpeedtestTranslationKey = keyof typeof SPEEDTEST_TRANSLATIONS["zh-CN"];

/**
 * 测速模块专属多语言 Hook，实时监听系统/全局语言设置
 *
 * @return 翻译函数与当前语言代码
 * @author iRouter
 * @since 2026-10-16
 */
export function useSpeedtestI18n() {
  const [locale, setLocale] = useState<string>("zh-CN");

  useEffect(() => {
    const raw = getCurrentLocale();
    if (raw.includes("tw") || raw.includes("hk") || raw.includes("hant")) {
      setLocale("zh-TW");
    } else if (raw.startsWith("zh")) {
      setLocale("zh-CN");
    } else {
      setLocale("en");
    }

    const unbind = onLocaleChange((newLoc) => {
      if (newLoc.includes("tw") || newLoc.includes("hk") || newLoc.includes("hant")) {
        setLocale("zh-TW");
      } else if (newLoc.startsWith("zh")) {
        setLocale("zh-CN");
      } else {
        setLocale("en");
      }
    });

    return () => unbind();
  }, []);

  const t = (key: SpeedtestTranslationKey, params?: Record<string, string | number>): string => {
    const dict = SPEEDTEST_TRANSLATIONS[locale as keyof typeof SPEEDTEST_TRANSLATIONS] || SPEEDTEST_TRANSLATIONS["zh-CN"];
    let text = dict[key] || SPEEDTEST_TRANSLATIONS["zh-CN"][key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      });
    }
    return text;
  };

  return { t, locale };
}
