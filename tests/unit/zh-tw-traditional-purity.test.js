// zh-TW 字典的繁体纯净度守卫。
//
// 背景：`public/i18n/literals/zh-TW.json` 长期混入简体字——例如
//   "这是您唯一一次看到此金鑰的机會。请妥善保管。"
// 一条译文里同时出现简体的「这」「机」「会」「请」和繁体的「金鑰」。
// 这类条目在繁体界面下会显示成简繁混杂的句子，是历次上游同步与手工补译
// 累积出来的质量问题。2026-10-30 用 OpenCC 官方字表批量校正了 804 条。
//
// 本守卫防止复发，断言两件事：
//   1. zh-TW 的**译文值**里不含简体专用字形（键是英文源串，不检查）；
//   2. 抽查若干高频技术术语，确认用的是繁体写法而非简体。
//
// 字表来源：OpenCC STCharacters（简体→繁体），只取「转换结果不等于自身」的字，
// 因此繁简同形字（如「清」「本」「中」）天然不会误报。
import { readFileSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, it, expect } from "vitest";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const TW_PATH = join(REPO, "public", "i18n", "literals", "zh-TW.json");
const tw = JSON.parse(readFileSync(TW_PATH, "utf8"));

// 简体专用字形（繁体中文里不会这样写）。只收录高置信度的一批，
// 覆盖历史上实际混入的那些字；宁可漏检也不误伤繁简同形字。
const SIMPLIFIED_ONLY = new Set([
  "这", "个", "们", "为", "对", "时", "会", "请", "让", "问", "说", "还",
  "过", "来", "么", "没", "当", "从", "与", "并", "应", "该", "认", "须",
  "题", "谁", "吗", "两", "无", "业", "务", "发", "开", "关", "闭", "变",
  "换", "设", "备", "连", "线", "数", "据", "库", "权", "标", "签", "证",
  "验", "输", "删", "编", "辑", "选", "择", "项", "复", "贴", "缓", "储",
  "宽", "带", "网", "络", "号", "码", "额", "费", "价", "钱", "买", "卖",
  "电", "话", "视", "频", "听", "读", "写", "记", "录", "载", "转", "进",
  "动", "静", "态", "势", "强", "优", "质", "级", "别", "类", "种", "样",
  "图", "档", "夹", "径", "层", "构", "计", "划", "产", "检", "测", "试",
  "细", "节", "总", "结", "汇", "报", "错", "误", "败", "毕", "终", "暂",
  "旧", "长", "边", "间", "处", "场", "确", "较", "异", "则", "将", "给",
  "达", "离", "归", "贷", "账", "户", "车", "马", "鸟", "鱼", "龙", "风",
  "云", "飞", "骑", "驾", "驶", "铁", "钢", "银", "针", "键", "盘", "机",
  "脑", "体", "显", "统", "览", "张", "湾", "页", "顺", "预", "领", "养",
  "训", "练", "语", "词", "译", "术", "艺", "声", "响", "乐", "戏", "剧",
  "极", "热", "爱", "欢", "庆", "贸", "货", "购", "销", "债", "偿", "赚",
  "赔", "虑", "忧", "惧", "恼", "愤", "惊", "讶", "赞", "誉", "论", "议",
  "评", "诉", "讼", "询", "讯", "访", "讲", "谈", "讨", "谢", "诺", "许",
  "订", "识", "忆", "怀", "惯", "怜", "悦", "悬", "恳", "惩", "惫", "惭",
  "愿", "懒", "灭", "灯", "灵", "灾", "炼", "烂", "烦", "烧", "爷", "牵",
  "牺", "犹", "狭", "狮", "独", "奖", "获", "环", "现", "玛", "珑", "亩",
]);

describe("zh-TW 字典繁体纯净度", () => {
  it("译文里不含简体专用字形", () => {
    const offenders = [];
    for (const [key, val] of Object.entries(tw)) {
      if (typeof val !== "string") continue;
      const found = [...new Set([...val].filter((ch) => SIMPLIFIED_ONLY.has(ch)))];
      if (found.length) {
        offenders.push({ key: key.slice(0, 50), value: val.slice(0, 60), chars: found.join("") });
      }
    }
    expect(
      offenders,
      offenders.length
        ? `zh-TW 有 ${offenders.length} 条混入简体字，前 5 条见下`
        : "",
    ).toEqual([]);
  });

  it("高频技术术语使用繁体写法", () => {
    const joined = Object.values(tw)
      .filter((v) => typeof v === "string")
      .join("\n");

    const probes = [
      ["瀏覽器", "浏览器"],
      ["檢查", "检查"],
      ["驗證", "验证"],
      ["設置", "设置"],
      ["測試", "测试"],
    ];

    for (const [trad, simp] of probes) {
      expect(
        joined.includes(simp),
        `zh-TW 里出现了简体写法「${simp}」，应为「${trad}」`,
      ).toBe(false);
    }
  });
});
